"""T034: after promotion, move the JOURNAL row of project_current/source_register.csv to the promoted revision (idempotent)."""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[2]
TASK = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from scripts.register_update import read_rows, update_rows  # noqa: E402

completed = {t: json.loads((ROOT / 'workflow' / 'completed' / f'{t}.json').read_text(encoding='utf-8')) for t in ('T033', 'T034')}
actual = hashlib.sha256((ROOT / 'journal' / 'D2_I95_Project_Journal.bpad').read_bytes()).hexdigest()
assert actual == completed['T034']['journal_sha256'], (actual, completed['T034']['journal_sha256'])
assert completed['T034']['previous_sha256'] == completed['T033']['journal_sha256']
previous = completed['T033']['journal_sha256']
NOTE = ('T034 / D-075 (22 October 2026): pier wall reconciled to the CAD geometry (219 x 36 in from EL 24.5264 to the cap bottom EL 40.76494, '
        '194.8625 in high): gravity sheet row 42 edited (E42 18 ft 3 in, G42 16 ft 2.8625 in; H42/J42/K42 caches recomputed, wall weight 114.737 to '
        '133.359 kip); C006 and C004 regenerated by their packages with the new journal values through their coherence gates; C017 regenerated from the '
        '22 October starting case (free length 92.4 in from the wall bottom; 1 failed check, grid clearance); PedBridge revision note and DecisionLog '
        'entry. FBMP pier export unchanged (wall load gap recorded as assumption A-012); native recalculation, appearance and engineering reviews not '
        'performed. See tasks/T034/verification.json.')
row = read_rows()['JOURNAL']
if row['sha256'] == actual:
    print('JOURNAL row already registered')
    raise SystemExit(0)
assert row['sha256'] == previous, row['sha256']
status = row['status'].replace('pier modules on the D-073 export', 'pier modules on the D-073 export; pier wall on the CAD geometry (D-075)')
written = update_rows({'JOURNAL': {'sha256': actual, 'registered_on': '2026-10-22', 'status': status, 'notes': NOTE}}, prepend_notes=True)
(TASK / 'adoption.json').write_text(json.dumps(dict(decision='D-075', task='T034', date='2026-10-22', journal_sha256=actual, previous_sha256=previous), indent=2) + '\n',
                                    encoding='utf-8')
print(json.dumps({'journal_sha256': actual, 'status': 'registered', 'row_status': written['JOURNAL']['status']}))
