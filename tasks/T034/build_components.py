# --- the gravity sheet row ---
raw = base.part(f'spreadsheet:{SHEET}')
text = raw.decode('utf-8')
nl = nl_of(text)
old_block = nl.join(' ' * 12 + c for c in OLD_ROW)
new_block = nl.join(' ' * 12 + c for c in NEW_ROW)
# the cached results of the old row are reproduced by the row's own arithmetic before the new ones are trusted
v, w, k = row_caches(*OLD_IN)
assert (f'{v:.10g}', f'{w:.13g}', f'{k:.13g}') == ('764.9140625', '114737.109375', '114.737109375'), (v, w, k)
v, w, k = row_caches(*NEW_IN)
assert abs(v - 889.06015625) < 1e-9 and abs(w - 133359.0234375) < 1e-6 and abs(k - 133.3590234375) < 1e-9, (v, w, k)
text = swap(text, old_block, new_block, 'gravity sheet row 42')
E.fromstring(text.encode('utf-8'))
sheet_bytes = text.encode('utf-8')
old_el, new_el = E.fromstring(raw), E.fromstring(sheet_bytes)
cells = lambda el: [(c.get('formula'), (c.findtext('num') or '').strip()) for c in el.iter('c')]
diff = [(a, b) for a, b in zip(cells(old_el), cells(new_el)) if a != b]
assert len(cells(old_el)) == len(cells(new_el)) and len(diff) == 5, diff
assert [a[0] for a, _ in diff] == [None, None, 'D42*E42*F42*G42', 'H42*I42', 'J42 to kip'], diff
assert Counter(c.get('formula') for c in old_el.iter('c')) == Counter(c.get('formula') for c in new_el.iter('c'))
out[f'spreadsheet:{SHEET}'] = sheet_bytes
record[SHEET] = {'source': 'base.bpad + row 42 (E42, G42 and the H42/J42/K42 caches)', 'changed_cells': diff,
                 'old_inputs_in': OLD_IN, 'new_inputs_in': NEW_IN}

